import { readFile, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
import {
  root,
  discoverSources,
  inspectSource,
  validateMetadata,
} from "./lib/tile-metadata.mjs";
const check = process.argv.includes("--validate");
const overrides = JSON.parse(
  await readFile(
    new URL("./tile-layout-overrides.json", import.meta.url),
    "utf8",
  ),
);
const paths = await discoverSources(),
  outputs = [],
  canonical = new Map();
const manifest = {
  schemaVersion: 1,
  ground: {},
  props: {},
  duplicates: [],
  renames: {
    "ground/send": "ground/sand",
    "props/volvano": "props/volcano",
    "props/trees/trees": "props/trees/living",
  },
};
for (const path of paths) {
  const m = await inspectSource(path, overrides[path]);
  outputs.push([path, m]);
  console.log(
    `${path}: ${m.slots.length} slots; confidence=${m.detection.confidence}; warnings=${m.warnings.length}`,
  );
}
// Fail atomically before touching any metadata if a source is ambiguous.
for (const [, m] of outputs) validateMetadata(m);
for (const [path, m] of outputs) {
  const duplicate = canonical.get(m.source.sha256);
  if (duplicate) {
    m.canonicalSource = duplicate;
    manifest.duplicates.push({
      source: path,
      canonical: duplicate,
      sha256: m.source.sha256,
    });
  } else {
    canonical.set(m.source.sha256, path);
    (manifest[m.kind === "ground" ? "ground" : "props"][m.family] ??= []).push(
      "./" + path.replace(".png", ".json"),
    );
  }
}
const serialize = (x) => JSON.stringify(x, null, 2) + "\n";
const files = outputs.map(([p, m]) => [
  new URL(p.replace(".png", ".json"), root),
  serialize(m),
]);
files.push([new URL("tiles.manifest.json", root), serialize(manifest)]);
let imports =
  "// Generated by assets:tiles:metadata. Static Next imports; no image loads at module scope.\n";
const entries = [];
for (const [i, [path]] of outputs
  .filter(([, m]) => !m.canonicalSource)
  .entries()) {
  imports += `import image${i} from "../assets/tiles/${path}";\nimport metadata${i} from "../assets/tiles/${path.replace(".png", ".json")}";\n`;
  entries.push(`  { image: image${i}, metadata: metadata${i} }`);
}
imports += `export const TILE_SOURCES = [\n${entries.join(",\n")}\n];\n`;
files.push([
  new URL("../src/game/client/tile-sources.generated.ts", import.meta.url),
  imports,
]);
for (const [path, content] of files) {
  if (check)
    assert.equal(
      await readFile(path, "utf8"),
      content,
      `${path}: stale metadata; regenerate`,
    );
  else await writeFile(path, content);
}
console.log(
  `${check ? "Validated" : "Generated"} ${outputs.length} sidecars, ${canonical.size} canonical atlases, manifest and static imports. Sources unchanged.`,
);
